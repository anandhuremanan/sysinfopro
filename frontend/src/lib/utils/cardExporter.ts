import { SaveSpecCardPNG } from '$lib/wailsjs/go/main/App';

export async function generateSpecCardPNG(systemInfo: any): Promise<string> {
	const canvas = document.createElement('canvas');
	canvas.width = 800;
	canvas.height = 450;
	const ctx = canvas.getContext('2d');
	if (!ctx) return '';

	// Dark sleek gradient background
	const bgGradient = ctx.createLinearGradient(0, 0, 800, 450);
	bgGradient.addColorStop(0, '#0f172a');
	bgGradient.addColorStop(1, '#1e293b');
	ctx.fillStyle = bgGradient;
	ctx.fillRect(0, 0, 800, 450);

	// Card Border & Glow
	ctx.strokeStyle = '#334155';
	ctx.lineWidth = 4;
	ctx.strokeRect(10, 10, 780, 430);

	// Header Banner
	ctx.fillStyle = '#38bdf8';
	ctx.font = 'bold 26px sans-serif';
	ctx.fillText('SysInfo Pro™ — System Specifications', 35, 50);

	ctx.fillStyle = '#94a3b8';
	ctx.font = '14px sans-serif';
	ctx.fillText(`${systemInfo.host_platform || 'Desktop System'} (${systemInfo.host_platform_version || ''}) • User: ${systemInfo.logged_in_user || ''}`, 35, 75);

	// Horizontal Line
	ctx.strokeStyle = '#334155';
	ctx.lineWidth = 1;
	ctx.beginPath();
	ctx.moveTo(35, 95);
	ctx.lineTo(765, 95);
	ctx.stroke();

	// Column 1: Processor
	drawSection(ctx, 35, 120, 'PROCESSOR', [
		['Model', systemInfo.cpu_model || 'Unknown'],
		['Vendor', systemInfo.cpu_vendor || 'Unknown'],
		['Cores', `${systemInfo.cpu_cores || 0} Cores`]
	]);

	// Column 2: Memory & Storage
	const ramGB = systemInfo.total_ram_mb ? (systemInfo.total_ram_mb / 1024).toFixed(1) : '0';
	drawSection(ctx, 290, 120, 'MEMORY & STORAGE', [
		['RAM', `${ramGB} GB Installed`],
		['Disk Type', systemInfo.disk_type || 'SSD'],
		['Storage', `${systemInfo.free_disk_gb || 0} GB free / ${systemInfo.total_disk_gb || 0} GB`]
	]);

	// Column 3: Network & OS
	drawSection(ctx, 545, 120, 'NETWORK & SYSTEM', [
		['Network', systemInfo.network_status || 'Connected'],
		['Platform', systemInfo.host_platform || 'Windows'],
		['OS Architecture', systemInfo.host_os || 'x64']
	]);

	// Bottom Branding Badge
	ctx.fillStyle = '#0284c7';
	ctx.fillRect(35, 370, 730, 40);

	ctx.fillStyle = '#ffffff';
	ctx.font = 'bold 13px sans-serif';
	ctx.fillText('Generated by SysInfo Pro 2.0 • Lightweight Cross-Platform Diagnostics', 50, 395);

	const dataUrl = canvas.toDataURL('image/png');
	return dataUrl;
}

function drawSection(ctx: CanvasRenderingContext2D, x: number, y: number, title: string, items: [string, string][]) {
	ctx.fillStyle = '#38bdf8';
	ctx.font = 'bold 12px sans-serif';
	ctx.fillText(title, x, y);

	let currentY = y + 28;
	items.forEach(([label, val]) => {
		ctx.fillStyle = '#94a3b8';
		ctx.font = '13px sans-serif';
		ctx.fillText(`${label}: `, x, currentY);

		const labelWidth = ctx.measureText(`${label}: `).width;
		ctx.fillStyle = '#f8fafc';
		ctx.font = 'bold 13px sans-serif';

		let displayVal = val;
		if (displayVal.length > 26) {
			displayVal = displayVal.substring(0, 24) + '...';
		}
		ctx.fillText(displayVal, x + labelWidth, currentY);
		currentY += 28;
	});
}

export async function exportSpecCardPNG(systemInfo: any): Promise<string> {
	const dataUrl = await generateSpecCardPNG(systemInfo);
	try {
		// @ts-ignore
		const savedPath = await SaveSpecCardPNG(dataUrl);
		return savedPath;
	} catch (err) {
		console.error('Failed to save spec card PNG:', err);
		return '';
	}
}
